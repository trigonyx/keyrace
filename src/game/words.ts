/** Random words, never the same word twice in a row. */
export function randomWords(count: number, random: () => number = Math.random): string[] {
  const out: string[] = [];
  while (out.length < count) {
    const w = WORDS[Math.floor(random() * WORDS.length)]!;
    if (w !== out[out.length - 1]) out.push(w);
  }
  return out;
}
